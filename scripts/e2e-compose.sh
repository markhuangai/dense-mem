pick_ports() {
  local count="$1"
  node - "$count" <<'NODE'
const net = require("node:net");
const count = Number(process.argv[2]);
const servers = [];

function listen() {
  return new Promise((resolve, reject) => {
    const server = net.createServer();
    server.once("error", reject);
    server.listen(0, "127.0.0.1", () => {
      servers.push(server);
      resolve(server.address().port);
    });
  });
}

(async () => {
  const ports = [];
  for (let i = 0; i < count; i += 1) {
    ports.push(await listen());
  }
  console.log(ports.join(" "));
  for (const server of servers) {
    server.close();
  }
})().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
NODE
}

env_file_value() {
  local field="$1"
  node - "$ROOT_ENV_FILE" "$field" <<'NODE'
const fs = require("node:fs");
const path = process.argv[2];
const target = process.argv[3];

function decodeValue(raw) {
  const value = raw.trim();
  if (value.startsWith('"') || value.startsWith("'")) {
    const quote = value[0];
    const closing = closingQuoteIndex(value, quote);
    if (closing > 0) {
      const inner = value.slice(1, closing);
      if (quote === "'") {
        return inner;
      }
      return inner
        .replace(/\\n/g, "\n")
        .replace(/\\r/g, "\r")
        .replace(/\\t/g, "\t")
        .replace(/\\"/g, '"')
        .replace(/\\\\/g, "\\");
    }
  }
  return stripInlineComment(value).trim();
}

function closingQuoteIndex(value, quote) {
  for (let index = 1; index < value.length; index += 1) {
    if (quote === '"' && value[index] === "\\" && index + 1 < value.length) {
      index += 1;
      continue;
    }
    if (value[index] === quote) {
      return index;
    }
  }
  return -1;
}

function stripInlineComment(value) {
  for (let index = 0; index < value.length; index += 1) {
    if (value[index] === "#" && (index === 0 || /\s/.test(value[index - 1]))) {
      return value.slice(0, index);
    }
  }
  return value;
}

let resolved;
for (const line of fs.readFileSync(path, "utf8").split(/\r?\n/)) {
  const match = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
  if (!match || match[1] !== target) {
    continue;
  }
  resolved = decodeValue(match[2]);
}
if (resolved !== undefined) {
  process.stdout.write(resolved);
} else {
  process.exit(1);
}
NODE
}

require_env_value() {
  local field="$1"
  local value=""
  if ! value="$(env_file_value "$field")" || [[ -z "$value" ]]; then
    echo "Missing required ${field} in ${ROOT_ENV_FILE}." >&2
    return 1
  fi
  printf '%s' "$value"
}

require_env_true() {
  local field="$1"
  local value=""
  value="$(require_env_value "$field")"
  case "$(printf '%s' "$value" | tr '[:upper:]' '[:lower:]')" in
    true|1|yes|y|on)
      return 0
      ;;
  esac
  echo "${field} must be true in ${ROOT_ENV_FILE} for compose e2e." >&2
  return 1
}

wait_for_url() {
  local label="$1"
  local url="$2"
  local header="${3:-}"
  for _ in $(seq 1 90); do
    if [[ -n "$header" ]]; then
      if curl -fsS -H "$header" "$url" >/dev/null 2>&1; then
        return 0
      fi
    elif curl -fsS "$url" >/dev/null 2>&1; then
      return 0
    fi
    sleep 2
  done
  echo "Timed out waiting for ${label} at ${url}" >&2
  return 1
}

