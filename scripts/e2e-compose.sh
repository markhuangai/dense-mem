prepare_e2e_compose_files() {
  if [[ ! -f "$COMPOSE_SOURCE_FILE" ]]; then
    echo "Missing supported compose source at ${COMPOSE_SOURCE_FILE}." >&2
    return 1
  fi
  E2E_COMPOSE_FILE="${ROOT_DIR}/docker-compose.e2e-${E2E_FILE_ID}.yml"
  node - "$COMPOSE_SOURCE_FILE" "$E2E_COMPOSE_FILE" "$E2E_ENV_FILE" "$E2E_PROMETHEUS_DIR" "$ROOT_DIR" "$E2E_SERVER_IMAGE" "$E2E_MARKER" <<'NODE'
const fs = require("node:fs");

const [sourcePath, destinationPath, envFile, prometheusDir, worktreeRoot, serverImage, marker] = process.argv.slice(2);
let compose = fs.readFileSync(sourcePath, "utf8");

function replaceRequired(pattern, replacement, label, expectedCount) {
  let count = 0;
  compose = compose.replace(pattern, (...args) => {
    count += 1;
    return typeof replacement === "function" ? replacement(...args) : replacement;
  });
  if ((expectedCount === undefined && count === 0) || (expectedCount !== undefined && count !== expectedCount)) {
    const expected = expectedCount === undefined ? "at least one" : expectedCount;
    throw new Error(`expected ${expected} ${label} replacement(s), found ${count}`);
  }
}

replaceRequired(/^(\s*-\s*)\.env\s*$/gm, (_, prefix) => `${prefix}${envFile}`, "env_file");
replaceRequired(/^(\s*context:\s*)\.\s*$/gm, (_, prefix) => `${prefix}${worktreeRoot}`, "build context", 1);
replaceRequired(/^(\s*image:\s*)ghcr\.io\/z-m-huang\/dense-mem:latest\s*$/gm, (_, prefix) => `${prefix}${serverImage}`, "server image", 1);
replaceRequired(
  /^(\s*)-\s+\.\/?prometheus\.yml:\/etc\/prometheus\/prometheus\.yml:ro\s*$/m,
  // Docker Desktop cannot reliably bind /tmp files; stage them through a Compose volume.
  (_, indent) => `${indent}- e2e-prometheus-config:/etc/prometheus`,
  "Prometheus config mount",
);
replaceRequired(
  /^(\s*)(?:file:\s*\.\/?telemetry-scrape-token|environment:\s*TELEMETRY_SCRAPE_TOKEN)\s*$/m,
  (_, indent) => `${indent}file: ${prometheusDir}/telemetry-scrape-token`,
  "telemetry secret source",
);
replaceRequired(
  /(^  prometheus:\r?\n[\s\S]*?)^    secrets:\r?\n      - telemetry-scrape-token\r?\n/m,
  (_, prometheusBlock) => prometheusBlock,
  "Prometheus secret block",
);
replaceRequired(/^volumes:\r?\n/m, "volumes:\n  e2e-prometheus-config:\n", "volume declarations", 1);

fs.writeFileSync(destinationPath, `${marker}\n${compose}`);
NODE
  if ! grep -F -- "$E2E_ENV_FILE" "$E2E_COMPOSE_FILE" >/dev/null || ! grep -F -- "e2e-prometheus-config:/etc/prometheus" "$E2E_COMPOSE_FILE" >/dev/null || ! grep -F -- "${E2E_PROMETHEUS_DIR}/telemetry-scrape-token" "$E2E_COMPOSE_FILE" >/dev/null || ! grep -F -- "context: ${ROOT_DIR}" "$E2E_COMPOSE_FILE" >/dev/null || ! grep -F -- "$E2E_SERVER_IMAGE" "$E2E_COMPOSE_FILE" >/dev/null; then
    echo "Generated compose file did not contain the expected E2E substitutions." >&2
    return 1
  fi
  COMPOSE_FILE="$E2E_COMPOSE_FILE"
}

