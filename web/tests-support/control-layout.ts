import AxeBuilder from "@axe-core/playwright";
import { expect, type Page, type TestInfo } from "@playwright/test";
import { navigate, expectPageContained, expectCompactNumberField, expectConflictCardsContained } from "./portal";

export async function checkControlLayout(page: Page, testInfo: TestInfo, width: number, theme: "light" | "dark") {
  await page.goto("/");
  await page.screenshot({ path: testInfo.outputPath("control-auth.png"), fullPage: true });
  await page.getByLabel("Control token").fill("secret");
  await page.getByRole("button", { name: "Unlock" }).click();
  await expect(page.getByRole("heading", { name: "Teams" })).toBeVisible();
  await expect(page.locator("html")).toHaveAttribute("data-theme", theme);
  await navigate(page, "Credentials");
  await expect(page.getByLabel("Credential name", { exact: true })).toBeVisible();
  await expectPageContained(page);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.screenshot({ path: testInfo.outputPath("control-credentials.png"), fullPage: true });
  await page.getByRole("button", { name: "Choose theme", exact: true }).click();
  await page.getByRole("menuitem", { name: theme === "light" ? "Light" : "Dark", exact: true }).click();
  await navigate(page, "Logs");
  await expect(page.getByRole("heading", { name: "Operation Logs", exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("control-logs.png"), fullPage: true });
  await page.goBack();
  await expect(page.getByLabel("Credential name", { exact: true })).toBeVisible();
  await page.goForward();
  await expect(page.getByRole("heading", { name: "Operation Logs", exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Operation Logs", exact: true })).toBeVisible();
  await expect(page.locator("html")).toHaveAttribute("data-theme", theme);
  await navigate(page, "Settings");
  await expect(page.getByRole("tablist", { name: "Settings sections" })).toBeVisible();
  const timezone = page.getByLabel("Timezone", { exact: true });
  const resetTimezone = page.getByRole("button", { name: "Clear Timezone override", exact: true });
  await expect(resetTimezone).toBeVisible();
  const timezoneBox = (await timezone.boundingBox())!;
  const resetBox = (await resetTimezone.boundingBox())!;
  expect(Math.abs(resetBox.y - timezoneBox.y)).toBeLessThanOrEqual(1);
  expect(resetBox.x).toBeGreaterThanOrEqual(timezoneBox.x + timezoneBox.width);
  await page.getByRole("tab", { name: "General", exact: true }).focus();
  await page.keyboard.press("ArrowRight");
  await expect(page.getByRole("tab", { name: "SSO runtime" })).toHaveAttribute("aria-selected", "true");
  await expectPageContained(page);
  await page.screenshot({ path: testInfo.outputPath("control-settings.png"), fullPage: true });
  await navigate(page, "Ontology maintenance");
  await expect(page.getByRole("group", { name: "Schedule", exact: true })).toBeVisible();
  await expect(page.getByRole("group", { name: "Processing", exact: true })).toBeVisible();
  await expect(page.getByRole("group", { name: "Allowance per window", exact: true })).toBeVisible();
  await expectCompactNumberField(page, "Cadence (hours)");
  await expectCompactNumberField(page, "Concurrent assessments");
  await expectCompactNumberField(page, "Input tokens per window");
  const timeWidth = (await page.getByLabel("Window start time", { exact: true }).boundingBox())!.width;
  expect(timeWidth).toBeGreaterThanOrEqual(80);
  expect(timeWidth).toBeLessThanOrEqual(136);
  const modelWidth = (await page.getByLabel("Maintenance model", { exact: true }).boundingBox())!.width;
  const cadenceWidth = (await page.getByLabel("Cadence (hours)", { exact: true }).boundingBox())!.width;
  expect(modelWidth).toBeGreaterThan(cadenceWidth);
  const coverage = page.getByRole("region", { name: "Ontology coverage", exact: true });
  await expect(coverage.getByRole("progressbar")).toHaveAttribute("aria-valuetext", "842 of 1,024");
  await expect(coverage).toContainText("Discovery in progress");
  await expect(coverage).toContainText("Eligible counts cover discovered records");
  await expect(page.getByRole("progressbar", { name: "Input tokens", exact: true })).toHaveAttribute("aria-valuetext", "160,000 of 251,000");
  await page.getByLabel("Cadence (hours)", { exact: true }).fill("24");
  await page.getByRole("button", { name: "Save config", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Changes saved");
  await expect(page.getByLabel("Cadence (hours)", { exact: true })).toHaveValue("24");
  const historyTable = page.getByRole("region", { name: "Ontology run history", exact: true }).locator('[data-slot="table-container"]');
  await historyTable.focus();
  await expect(historyTable).toBeFocused();
  if (width === 390) {
    await page.keyboard.press("ArrowRight");
    await expect.poll(() => historyTable.evaluate((element) => element.scrollLeft)).toBeGreaterThan(0);
  }
  await expectPageContained(page);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.screenshot({ path: testInfo.outputPath("control-ontology.png"), fullPage: true });
  await navigate(page, "Conflicts");
  await page.getByRole("tab", { name: "Evidence", exact: true }).click();
  await expect(page.locator(".evidence-conflict-card")).toHaveCount(3);
  await expectConflictCardsContained(page);
  await expectPageContained(page);
  await page.screenshot({ path: testInfo.outputPath("control-evidence-conflicts.png"), fullPage: true });
}
