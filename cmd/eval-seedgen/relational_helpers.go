package main

import (
	"fmt"
	"strings"
	"time"

	"github.com/markhuangai/dense-mem/internal/evalharness"
)

func relationalCorpusItem(seedID, sourceDocID, title, content, category, role string, quality float64, caseID string, claim evalharness.TypedClaim) evalharness.CorpusItem {
	claim.IdempotencyKey = fmt.Sprintf("eval:%s:claim:1", sourceDocID)
	if claim.ExtractConf == 0 {
		claim.ExtractConf = 0.98
	}
	if claim.ResolutionConf == 0 {
		claim.ResolutionConf = 0.98
	}
	if claim.ExtractionModel == "" {
		claim.ExtractionModel = "dense-mem.eval-relational-seedgen"
	}
	if claim.ExtractionVersion == "" {
		claim.ExtractionVersion = "v1"
	}
	if claim.PipelineRunID == "" {
		claim.PipelineRunID = "eval:" + sourceDocID
	}
	if claim.Classification == nil {
		claim.Classification = map[string]any{}
	}
	claim.Classification["confidentiality"] = "public"
	claim.Classification["pii"] = "synthetic"
	return evalharness.CorpusItem{
		SourceDocID:   sourceDocID,
		Title:         title,
		Content:       content,
		SourceDataset: seedID,
		SourceType:    "synthetic",
		Authority:     role,
		SourceQuality: quality,
		Labels:        []string{"eval", "relational", category, role},
		Metadata: map[string]any{
			"case_id": caseID,
			"role":    role,
		},
		Claims:      []evalharness.TypedClaim{claim},
		AutoPromote: role == "required" || role == "hard_negative",
	}
}

func relationalClaim(subject, predicate, object, validFrom, validTo string) evalharness.TypedClaim {
	return evalharness.TypedClaim{
		Subject:        subject,
		Predicate:      predicate,
		Object:         object,
		Modality:       "asserted",
		Polarity:       "positive",
		ExtractConf:    0.98,
		ResolutionConf: 0.98,
		ValidFrom:      datePtr(validFrom),
		ValidTo:        datePtr(validTo),
		Classification: map[string]any{
			"confidentiality": "public",
			"pii":             "synthetic",
		},
	}
}

func typedFactSourceDocID(sourceDocID string, index int) string {
	return fmt.Sprintf("%s:fact:%d", sourceDocID, index)
}

func datePtr(value string) *time.Time {
	parsed, err := time.Parse("2006-01-02", value)
	if err != nil {
		panic(err)
	}
	return &parsed
}

func relationalEvalLicense(seedID string) string {
	return strings.TrimSpace(fmt.Sprintf(`# %s Licenses

This seed is synthetic project-local relational evaluation data generated by cmd/eval-seedgen.

It contains no production data and no third-party source text. Use it for local
Dense-Mem recall, evidence, and dream-hypothesis quality tests within this repository.
`, seedID)) + "\n"
}
