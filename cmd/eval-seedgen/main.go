const presetLocalEval1KV2 = "local_eval_1k_v2"

type generatedCase struct {
	Case          evalharness.Case
	SuiteCase     evalharness.SuiteCase
	Corpus        []evalharness.CorpusItem
	QRel          evalharness.QRel
	Answer        evalharness.AnswerLabel
	HardNegatives []hardNegativeRow
	Transform     transformRow
}

type hardNegativeRow struct {
	CaseID      string `json:"case_id"`
	Category    string `json:"category"`
	SourceDocID string `json:"source_doc_id"`
	Reason      string `json:"reason"`
}

type transformRow struct {
	CaseID        string `json:"case_id"`
	Category      string `json:"category"`
	Transform     string `json:"transform"`
	DocsPerCase   int    `json:"docs_per_case"`
	RequiredDocID string `json:"required_doc_id"`
}

type scenario struct {
	Category        string
	Query           string
	RequiredTitle   string
	RequiredContent string
	BadTitles       []string
	BadContents     []string
	Answer          string
	MustInclude     []string
	MustNotInclude  []string
	Expected        string
}

type categorySpec struct {
	Name      string
	Code      string
	Transform string
}

func main() {
	preset := flag.String("preset", presetLocalEval1KV2, "seed preset to generate")
	outDir := flag.String("out", filepath.Join("tests", "eval", "seeds", presetLocalEval1KV2), "seed output directory")
	suitePath := flag.String("suite", filepath.Join("tests", "eval", "suites", presetLocalEval1KV2+".jsonl"), "suite JSONL output path")
	flag.Parse()

	if *preset != presetLocalEval1KV2 {
		exitf("unsupported preset %q", *preset)
	}
	if err := generateLocalEval1KV2(*outDir, *suitePath); err != nil {
		exitf("generate seed: %v", err)
	}
	fmt.Printf("generated %s in %s and %s\n", *preset, *outDir, *suitePath)
}

func generateLocalEval1KV2(outDir, suitePath string) error {
	generated := buildLocalEval1KV2()
	manifest := evalharness.SeedManifest{
		SchemaVersion:     evalharness.SeedSchemaVersion,
		SeedID:            presetLocalEval1KV2,
		Description:       "Deterministic 1k local eval seed for recall ranking and misleading-memory regressions.",
		GeneratedAt:       "2026-06-28T00:00:00Z",
		CorpusFile:        "corpus.jsonl",
		CasesFile:         "cases.jsonl",
		QrelsFile:         "qrels.jsonl",
		AnswersFile:       "answers.jsonl",
		HardNegativesFile: "hard_negatives.jsonl",
		TransformsFile:    "transforms.jsonl",
		LicensesFile:      "licenses.md",
		Counts: map[string]int{
			"cases":             1000,
			"corpus":            4000,
			"docs_per_case":     4,
			"qrels":             1000,
			"answers":           1000,
			"transforms":        1000,
			"hard_negatives":    3000,
			"sanity_cases":      100,
			"adversarial_cases": 900,
		},
		Sources: []evalharness.SeedSource{
			{
				Name:    "dense-mem synthetic local eval seed",
				License: "Project-local synthetic data",
				Notes:   "Generated by cmd/eval-seedgen; contains no third-party source text.",
			},
		},
	}

	corpus := make([]evalharness.CorpusItem, 0, 4000)
	cases := make([]evalharness.Case, 0, 1000)
	qrels := make([]evalharness.QRel, 0, 1000)
	answers := make([]evalharness.AnswerLabel, 0, 1000)
	hardNegatives := make([]hardNegativeRow, 0, 3000)
	transforms := make([]transformRow, 0, 1000)
	suite := make([]evalharness.SuiteCase, 0, 1000)
	for _, item := range generated {
		corpus = append(corpus, item.Corpus...)
		cases = append(cases, item.Case)
		qrels = append(qrels, item.QRel)
		answers = append(answers, item.Answer)
		hardNegatives = append(hardNegatives, item.HardNegatives...)
		transforms = append(transforms, item.Transform)
		suite = append(suite, item.SuiteCase)
	}
	if err := writeJSONFile(filepath.Join(outDir, "seed_manifest.json"), manifest); err != nil {
		return err
	}
	if err := writeJSONL(filepath.Join(outDir, "corpus.jsonl"), corpus); err != nil {
		return err
	}
	if err := writeJSONL(filepath.Join(outDir, "cases.jsonl"), cases); err != nil {
		return err
	}
	if err := writeJSONL(filepath.Join(outDir, "qrels.jsonl"), qrels); err != nil {
		return err
	}
	if err := writeJSONL(filepath.Join(outDir, "answers.jsonl"), answers); err != nil {
		return err
	}
	if err := writeJSONL(filepath.Join(outDir, "hard_negatives.jsonl"), hardNegatives); err != nil {
		return err
	}
	if err := writeJSONL(filepath.Join(outDir, "transforms.jsonl"), transforms); err != nil {
		return err
	}
	if err := writeText(filepath.Join(outDir, "licenses.md"), localEvalLicense()); err != nil {
		return err
	}
	return writeJSONL(suitePath, suite)
}

func buildLocalEval1KV2() []generatedCase {
	out := make([]generatedCase, 0, 1000)
	for i := 1; i <= 100; i++ {
		out = append(out, buildCase(sanityScenario(i), i, false, "sanity", "sanity_case"))
	}
	globalIndex := 101
	for _, category := range adversarialCategories() {
		for i := 1; i <= 90; i++ {
			out = append(out, buildCase(adversarialScenario(category, i), globalIndex, true, category.Name, category.Transform))
			globalIndex++
		}
	}
	return out
}

func buildCase(s scenario, globalIndex int, adversarial bool, category, transform string) generatedCase {
	caseID := fmt.Sprintf("%s_%04d", presetLocalEval1KV2, globalIndex)
	requiredDocID := caseID + "_required"
	badDocIDs := []string{caseID + "_negative_01", caseID + "_negative_02", caseID + "_negative_03"}
	slices := []string{"sanity"}
	difficulty := "easy"
	if adversarial {
		slices = []string{"adversarial", category}
		difficulty = "hard"
	}
	corpus := []evalharness.CorpusItem{
		corpusItem(requiredDocID, s.RequiredTitle, s.RequiredContent, category, "required", 1.0, caseID),
	}
	for i := range badDocIDs {
		corpus = append(corpus, corpusItem(badDocIDs[i], s.BadTitles[i], s.BadContents[i], category, "hard_negative", 0.2, caseID))
	}
	badRefs := make([]evalharness.Ref, 0, len(badDocIDs))
	hardNegatives := make([]hardNegativeRow, 0, len(badDocIDs))
	for _, docID := range badDocIDs {
		badRefs = append(badRefs, evalharness.Ref{Type: "source_doc", SourceDocID: docID, Grade: -1, Reason: "misleading local eval decoy"})
		hardNegatives = append(hardNegatives, hardNegativeRow{
			CaseID:      caseID,
			Category:    category,
			SourceDocID: docID,
			Reason:      "Similar wording to the query but conflicts with the required record.",
		})
	}
	tc := evalharness.Case{
		CaseID:           caseID,
		Query:            s.Query,
		TaskType:         "memory_recall",
		Difficulty:       difficulty,
		Slices:           slices,
		ExpectedBehavior: s.Expected,
		ValidAt:          "2026-06-28T00:00:00Z",
		KnownAt:          "2026-06-28T00:00:00Z",
		Limit:            5,
	}
	return generatedCase{
		Case:      tc,
		SuiteCase: evalharness.SuiteCase{CaseID: caseID, Weight: 1, Slices: slices},
		Corpus:    corpus,
		QRel: evalharness.QRel{
			CaseID:       caseID,
			RequiredRefs: []evalharness.Ref{{Type: "source_doc", SourceDocID: requiredDocID, Grade: 3, Reason: "canonical local eval record"}},
			BadRefs:      badRefs,
		},
		Answer: evalharness.AnswerLabel{
			CaseID:             caseID,
			ReferenceAnswer:    s.Answer,
			MustInclude:        s.MustInclude,
			MustNotInclude:     s.MustNotInclude,
			ExpectedBehavior:   s.Expected,
			GroundednessPolicy: "Use the required source_doc and avoid hard-negative source_docs.",
		},
		HardNegatives: hardNegatives,
		Transform: transformRow{
			CaseID:        caseID,
			Category:      category,
			Transform:     transform,
			DocsPerCase:   4,
			RequiredDocID: requiredDocID,
		},
	}
}

func corpusItem(sourceDocID, title, content, category, role string, quality float64, caseID string) evalharness.CorpusItem {
	return evalharness.CorpusItem{
		SourceDocID:   sourceDocID,
		Title:         title,
		Content:       content,
		SourceDataset: presetLocalEval1KV2,
		SourceType:    "synthetic",
		Authority:     role,
		SourceQuality: quality,
		Labels:        []string{"eval", category, role},
		Metadata: map[string]any{
			"case_id": caseID,
			"role":    role,
		},
	}
}

func sanityScenario(i int) scenario {
	entity := fmt.Sprintf("account L%04d", i)
	currentOwner := fmt.Sprintf("team-%03d-blue", i)
	oldOwner := fmt.Sprintf("team-%03d-red", i)
	draftOwner := fmt.Sprintf("team-%03d-draft", i)
	neighborOwner := fmt.Sprintf("team-%03d-blue", i+100)
	return scenario{
		Category:        "sanity",
		Query:           fmt.Sprintf("Who is the current primary owner for %s?", entity),
		RequiredTitle:   fmt.Sprintf("Current owner registry for %s", entity),
		RequiredContent: fmt.Sprintf("Canonical owner registry dated 2026-06-28. The current primary owner for %s is %s.", entity, currentOwner),
		BadTitles: []string{
			fmt.Sprintf("Legacy owner note for %s", entity),
			fmt.Sprintf("Draft owner proposal for %s", entity),
			fmt.Sprintf("Neighbor account owner note for L%04d", i+100),
		},
		BadContents: []string{
			fmt.Sprintf("Legacy note from 2025. %s previously used %s before the ownership migration.", entity, oldOwner),
			fmt.Sprintf("Unapproved draft. A proposed owner for %s was %s, but the proposal was not adopted.", entity, draftOwner),
			fmt.Sprintf("Neighbor account L%04d currently uses %s. This note is not about %s.", i+100, neighborOwner, entity),
		},
		Answer:         fmt.Sprintf("The current primary owner for %s is %s.", entity, currentOwner),
		MustInclude:    []string{currentOwner},
		MustNotInclude: []string{oldOwner, draftOwner, neighborOwner},
		Expected:       "Return the current owner from the canonical registry and ignore legacy, draft, and neighbor records.",
	}
}

func adversarialCategories() []categorySpec {
	return []categorySpec{
		{Name: "obsolete_correction", Code: "OBS", Transform: "newer canonical correction overrides stale memory"},
		{Name: "explicit_negation", Code: "NEG", Transform: "required document contains an explicit negation that should not be inverted"},
		{Name: "alias_collision", Code: "ALS", Transform: "similar aliases share terms but refer to different entities"},
		{Name: "temporal_validity", Code: "TMP", Transform: "valid-at date selects the current fact over old facts"},
		{Name: "quoted_false_claim", Code: "QFC", Transform: "quoted claim is false and must not be treated as the answer"},
		{Name: "scope_collision", Code: "SCP", Transform: "query scope must match region or product scope"},
		{Name: "authority_conflict", Code: "AUT", Transform: "authoritative runbook beats informal notes"},
		{Name: "retraction", Code: "RET", Transform: "retraction invalidates an earlier announcement"},
		{Name: "unit_trap", Code: "UNT", Transform: "units differ while numbers are intentionally similar"},
		{Name: "conditional_exception", Code: "CND", Transform: "conditional rule selects an exception path"},
	}
}

func adversarialScenario(category categorySpec, i int) scenario {
	switch category.Name {
	case "obsolete_correction":
		service := fmt.Sprintf("service %s-%03d", category.Code, i)
		current := fmt.Sprintf("03:%02d UTC", i%60)
		old := fmt.Sprintf("02:%02d UTC", i%60)
		return scenario{
			Category:        category.Name,
			Query:           fmt.Sprintf("What is the current deployment window for %s?", service),
			RequiredTitle:   fmt.Sprintf("Corrected deployment window for %s", service),
			RequiredContent: fmt.Sprintf("Current release calendar update dated 2026-06-28. %s now deploys at %s; older 02:xx windows are obsolete.", service, current),
			BadTitles: []string{
				fmt.Sprintf("Old release calendar for %s", service),
				fmt.Sprintf("Migration draft for %s", service),
				fmt.Sprintf("Incident note mentioning %s", service),
			},
			BadContents: []string{
				fmt.Sprintf("Archived 2025 calendar. %s deployed at %s before the correction.", service, old),
				fmt.Sprintf("Draft migration plan suggested %s for %s, but the plan was replaced.", old, service),
				fmt.Sprintf("An incident review copied the obsolete %s window for %s while discussing a rollback.", old, service),
			},
			Answer:         fmt.Sprintf("%s currently deploys at %s.", service, current),
			MustInclude:    []string{current},
			MustNotInclude: []string{old},
			Expected:       "Prefer the corrected current release calendar over older copied windows.",
		}
	case "explicit_negation":
		queue := fmt.Sprintf("queue %s-%03d", category.Code, i)
		allowed := fmt.Sprintf("pager-%03d-green", i)
		blocked := fmt.Sprintf("pager-%03d-red", i)
		return scenario{
			Category:        category.Name,
			Query:           fmt.Sprintf("Which pager should alerts for %s use?", queue),
			RequiredTitle:   fmt.Sprintf("Alert routing rule for %s", queue),
			RequiredContent: fmt.Sprintf("Routing policy dated 2026-06-28. Alerts for %s must use %s. Do not use %s for this queue.", queue, allowed, blocked),
			BadTitles: []string{
				fmt.Sprintf("Negated pager note for %s", queue),
				fmt.Sprintf("Pager deprecation notice for %s", queue),
				fmt.Sprintf("Old escalation map for %s", queue),
			},
			BadContents: []string{
				fmt.Sprintf("Troubleshooting note says: not %s for %s. The forbidden pager appears near the queue name.", blocked, queue),
				fmt.Sprintf("%s was removed from %s after false positives.", blocked, queue),
				fmt.Sprintf("Before 2026, %s used %s for alerts.", queue, blocked),
			},
			Answer:         fmt.Sprintf("Alerts for %s should use %s.", queue, allowed),
			MustInclude:    []string{allowed},
			MustNotInclude: []string{blocked},
			Expected:       "Keep the negation intact and do not rank the forbidden pager note as support.",
		}
	case "alias_collision":
		exact := fmt.Sprintf("Atlas Core %03d", i)
		alias := fmt.Sprintf("Atlas Lite %03d", i)
		code := fmt.Sprintf("AC-%04d", i)
		wrong := fmt.Sprintf("AL-%04d", i)
		return scenario{
			Category:        category.Name,
			Query:           fmt.Sprintf("What registry code belongs to %s?", exact),
			RequiredTitle:   fmt.Sprintf("Registry entry for %s", exact),
			RequiredContent: fmt.Sprintf("Canonical registry. %s has registry code %s. Do not confuse it with %s.", exact, code, alias),
			BadTitles: []string{
				fmt.Sprintf("Registry entry for %s", alias),
				fmt.Sprintf("Alias memo for Atlas %03d", i),
				fmt.Sprintf("Deprecated code table for %s", exact),
			},
			BadContents: []string{
				fmt.Sprintf("%s is a separate product and has registry code %s.", alias, wrong),
				fmt.Sprintf("The short alias Atlas %03d was used for %s in a sales memo.", i, alias),
				fmt.Sprintf("A deprecated code table listed %s as AC-OLD-%03d before reassignment.", exact, i),
			},
			Answer:         fmt.Sprintf("%s belongs to registry code %s.", exact, code),
			MustInclude:    []string{code},
			MustNotInclude: []string{wrong, fmt.Sprintf("AC-OLD-%03d", i)},
			Expected:       "Match the exact entity name and avoid the similar alias.",
		}
	case "temporal_validity":
		policy := fmt.Sprintf("policy %s-%03d", category.Code, i)
		current := fmt.Sprintf("retention-%03d-current", i)
		old := fmt.Sprintf("retention-%03d-legacy", i)
		return scenario{
			Category:        category.Name,
			Query:           fmt.Sprintf("As of 2026-06-28, which retention label applies to %s?", policy),
			RequiredTitle:   fmt.Sprintf("Current retention label for %s", policy),
			RequiredContent: fmt.Sprintf("Policy register valid on 2026-06-28. %s uses retention label %s.", policy, current),
			BadTitles: []string{
				fmt.Sprintf("2024 retention label for %s", policy),
				fmt.Sprintf("2025 transition note for %s", policy),
				fmt.Sprintf("Future proposal for %s", policy),
			},
			BadContents: []string{
				fmt.Sprintf("Policy register valid on 2024-11-01. %s used retention label %s.", policy, old),
				fmt.Sprintf("Transition note from 2025 says %s would keep %s until migration finished.", policy, old),
				fmt.Sprintf("Future proposal says %s might move to retention-%03d-future, but it is not active.", policy, i),
			},
			Answer:         fmt.Sprintf("As of 2026-06-28, %s uses %s.", policy, current),
			MustInclude:    []string{current},
			MustNotInclude: []string{old, fmt.Sprintf("retention-%03d-future", i)},
			Expected:       "Use the fact valid at the query date.",
		}
	case "quoted_false_claim":
		ticket := fmt.Sprintf("ticket %s-%03d", category.Code, i)
		trueStatus := fmt.Sprintf("blocked-by-review-%03d", i)
		falseStatus := fmt.Sprintf("approved-%03d", i)
		return scenario{
			Category:        category.Name,
			Query:           fmt.Sprintf("What is the verified status of %s?", ticket),
			RequiredTitle:   fmt.Sprintf("Verification note for %s", ticket),
			RequiredContent: fmt.Sprintf("Verification note dated 2026-06-28. The phrase %q was quoted in the report as a false claim. The verified status of %s is %s.", falseStatus, ticket, trueStatus),
			BadTitles: []string{
				fmt.Sprintf("Report excerpt for %s", ticket),
				fmt.Sprintf("Forwarded claim about %s", ticket),
				fmt.Sprintf("Rumor summary for %s", ticket),
			},
			BadContents: []string{
				fmt.Sprintf("Report excerpt quotes an unsupported claim: %s is %s.", ticket, falseStatus),
				fmt.Sprintf("Forwarded message repeats that %s was %s, without verification.", ticket, falseStatus),
				fmt.Sprintf("Rumor summary lists %s next to %s, but later review rejected it.", ticket, falseStatus),
			},
			Answer:         fmt.Sprintf("The verified status of %s is %s.", ticket, trueStatus),
			MustInclude:    []string{trueStatus},
			MustNotInclude: []string{falseStatus},
			Expected:       "Do not treat a quoted false claim as the verified answer.",
		}
	case "scope_collision":
		region := fmt.Sprintf("west-%03d", i)
		otherRegion := fmt.Sprintf("east-%03d", i)
		current := fmt.Sprintf("endpoint-w-%03d", i)
		wrong := fmt.Sprintf("endpoint-e-%03d", i)
		return scenario{
			Category:        category.Name,
			Query:           fmt.Sprintf("Which endpoint should the %s region use for billing sync?", region),
			RequiredTitle:   fmt.Sprintf("Billing sync endpoint for %s", region),
			RequiredContent: fmt.Sprintf("Regional billing sync map. The %s region uses endpoint %s.", region, current),
			BadTitles: []string{
				fmt.Sprintf("Billing sync endpoint for %s", otherRegion),
				fmt.Sprintf("Global billing sync default %03d", i),
				fmt.Sprintf("Regional migration note %03d", i),
			},
			BadContents: []string{
				fmt.Sprintf("The %s region uses endpoint %s. This entry is not scoped to %s.", otherRegion, wrong, region),
				fmt.Sprintf("Global default endpoint default-%03d applies only when no regional endpoint is configured.", i),
				fmt.Sprintf("Migration note copied %s beside %s while describing a past cross-region test.", wrong, region),
			},
			Answer:         fmt.Sprintf("The %s region should use %s for billing sync.", region, current),
			MustInclude:    []string{current},
			MustNotInclude: []string{wrong, fmt.Sprintf("default-%03d", i)},
			Expected:       "Respect the region in the query and ignore other-region/default entries.",
		}
	case "authority_conflict":
		runbook := fmt.Sprintf("runbook AUT-%03d", i)
		current := fmt.Sprintf("procedure-%03d-canonical", i)
		informal := fmt.Sprintf("procedure-%03d-chat", i)
		return scenario{
			Category:        category.Name,
			Query:           fmt.Sprintf("Which procedure does %s require?", runbook),
			RequiredTitle:   fmt.Sprintf("Authoritative procedure for %s", runbook),
			RequiredContent: fmt.Sprintf("Authoritative runbook signed by operations. %s requires %s.", runbook, current),
			BadTitles: []string{
				fmt.Sprintf("Chat note about %s", runbook),
				fmt.Sprintf("Personal checklist for %s", runbook),
				fmt.Sprintf("Meeting transcript for %s", runbook),
			},
			BadContents: []string{
				fmt.Sprintf("An informal chat suggested %s for %s, but it was not approved.", informal, runbook),
				fmt.Sprintf("A personal checklist used %s while testing %s.", informal, runbook),
				fmt.Sprintf("Meeting transcript mentioned %s as an option before the runbook was signed.", informal),
			},
			Answer:         fmt.Sprintf("%s requires %s.", runbook, current),
			MustInclude:    []string{current},
			MustNotInclude: []string{informal},
			Expected:       "Rank the authoritative runbook above informal conflicting notes.",
		}
	case "retraction":
		notice := fmt.Sprintf("notice RET-%03d", i)
		current := fmt.Sprintf("launch-paused-%03d", i)
		retracted := fmt.Sprintf("launch-approved-%03d", i)
		return scenario{
			Category:        category.Name,
			Query:           fmt.Sprintf("What is the active launch decision for %s?", notice),
			RequiredTitle:   fmt.Sprintf("Retraction update for %s", notice),
			RequiredContent: fmt.Sprintf("Retraction update dated 2026-06-28. Earlier approval for %s was withdrawn. The active decision is %s.", notice, current),
			BadTitles: []string{
				fmt.Sprintf("Original launch announcement for %s", notice),
				fmt.Sprintf("Forwarded approval for %s", notice),
				fmt.Sprintf("Calendar hold for %s", notice),
			},
			BadContents: []string{
				fmt.Sprintf("Original announcement said %s was %s before the retraction.", notice, retracted),
				fmt.Sprintf("Forwarded approval repeats %s for %s but predates the withdrawal.", retracted, notice),
				fmt.Sprintf("Calendar hold copied the old %s decision and was not updated.", retracted),
			},
			Answer:         fmt.Sprintf("The active launch decision for %s is %s.", notice, current),
			MustInclude:    []string{current},
			MustNotInclude: []string{retracted},
			Expected:       "Use the retraction update and not the withdrawn announcement.",
		}
	case "unit_trap":
		job := fmt.Sprintf("job UNT-%03d", i)
		current := fmt.Sprintf("%d minutes", 10+i%20)
		wrongSeconds := fmt.Sprintf("%d seconds", 10+i%20)
		wrongHours := fmt.Sprintf("%d hours", 10+i%20)
		return scenario{
			Category:        category.Name,
			Query:           fmt.Sprintf("What timeout should %s use?", job),
			RequiredTitle:   fmt.Sprintf("Timeout setting for %s", job),
			RequiredContent: fmt.Sprintf("Runtime configuration. %s must use a timeout of %s.", job, current),
			BadTitles: []string{
				fmt.Sprintf("Seconds timeout example for %s", job),
				fmt.Sprintf("Hours timeout incident for %s", job),
				fmt.Sprintf("Numeric-only timeout note for %s", job),
			},
			BadContents: []string{
				fmt.Sprintf("A test example used %s for %s, which is too short for production.", wrongSeconds, job),
				fmt.Sprintf("An incident note says %s accidentally used %s during a stuck retry.", job, wrongHours),
				fmt.Sprintf("Numeric-only note lists %d without units and should not override the runtime configuration.", 10+i%20),
			},
			Answer:         fmt.Sprintf("%s should use a timeout of %s.", job, current),
			MustInclude:    []string{current},
			MustNotInclude: []string{wrongSeconds, wrongHours},
			Expected:       "Preserve the unit attached to the timeout value.",
		}
	case "conditional_exception":
		tenant := fmt.Sprintf("tenant CND-%03d enterprise", i)
		current := fmt.Sprintf("endpoint-enterprise-%03d", i)
		defaultEndpoint := fmt.Sprintf("endpoint-standard-%03d", i)
		legacy := fmt.Sprintf("endpoint-legacy-%03d", i)
		return scenario{
			Category:        category.Name,
			Query:           fmt.Sprintf("Which endpoint should %s use for export?", tenant),
			RequiredTitle:   fmt.Sprintf("Conditional export rule for %s", tenant),
			RequiredContent: fmt.Sprintf("Export routing rule. Enterprise tenants such as %s must use %s. Standard tenants use %s.", tenant, current, defaultEndpoint),
			BadTitles: []string{
				fmt.Sprintf("Standard export rule %03d", i),
				fmt.Sprintf("Legacy enterprise export rule %03d", i),
				fmt.Sprintf("Fallback endpoint note %03d", i),
			},
			BadContents: []string{
				fmt.Sprintf("Standard tenants use %s for export. This does not apply to %s.", defaultEndpoint, tenant),
				fmt.Sprintf("Legacy enterprise tenants once used %s before the conditional rule changed.", legacy),
				fmt.Sprintf("Fallback endpoint %s applies only when tenant tier is unknown.", defaultEndpoint),
			},
			Answer:         fmt.Sprintf("%s should use %s for export.", tenant, current),
			MustInclude:    []string{current},
			MustNotInclude: []string{defaultEndpoint, legacy},
			Expected:       "Apply the enterprise exception rather than the standard/default branch.",
		}
	default:
		panic("unhandled category: " + category.Name)
	}
}

func writeJSONFile(path string, value any) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	encoder := json.NewEncoder(f)
	encoder.SetIndent("", "  ")
	return encoder.Encode(value)
}

func writeJSONL[T any](path string, rows []T) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	encoder := json.NewEncoder(f)
	for _, row := range rows {
		if err := encoder.Encode(row); err != nil {
			return err
		}
	}
	return nil
}

func writeText(path, value string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(value), 0o644)
}

