const (
	presetLocalEval1KV2            = "local_eval_1k_v2"
	presetLocalEvalRelational1KV1  = "local_eval_relational_1k_v1"
	presetLocalTrainRelational100K = "local_train_relational_100k_v1"
	presetFeedbackRecallHardcases  = "feedback_recall_hardcases_v1"
)

type generatedCase struct {
	Case          evalharness.Case
	SuiteCase     evalharness.SuiteCase
	Corpus        []evalharness.CorpusItem
	QRel          evalharness.QRel
	Answer        evalharness.AnswerLabel
	HardNegatives []hardNegativeRow
	Transform     transformRow
	Dreams        []evalharness.ExpectedDream
}

type hardNegativeRow struct {
	CaseID      string `json:"case_id"`
	Category    string `json:"category"`
	SourceDocID string `json:"source_doc_id"`
	Reason      string `json:"reason"`
}

type transformRow struct {
	CaseID        string `json:"case_id"`
	Category      string `json:"category"`
	Transform     string `json:"transform"`
	DocsPerCase   int    `json:"docs_per_case"`
	RequiredDocID string `json:"required_doc_id"`
}

type scenario struct {
	Category        string
	Query           string
	RequiredTitle   string
	RequiredContent string
	BadTitles       []string
	BadContents     []string
	Answer          string
	MustInclude     []string
	MustNotInclude  []string
	Expected        string
}

type categorySpec struct {
	Name      string
	Code      string
	Transform string
}

func main() {
	preset := flag.String("preset", presetLocalEval1KV2, "seed preset to generate")
	outDir := flag.String("out", filepath.Join("tests", "eval", "seeds", presetLocalEval1KV2), "seed output directory")
	suitePath := flag.String("suite", filepath.Join("tests", "eval", "suites", presetLocalEval1KV2+".jsonl"), "suite JSONL output path")
	flag.Parse()
	outProvided := false
	suiteProvided := false
	flag.Visit(func(f *flag.Flag) {
		switch f.Name {
		case "out":
			outProvided = true
		case "suite":
			suiteProvided = true
		}
	})
	if !outProvided {
		*outDir = filepath.Join("tests", "eval", "seeds", *preset)
	}
	if !suiteProvided {
		*suitePath = filepath.Join("tests", "eval", "suites", *preset+".jsonl")
	}

	switch *preset {
	case presetLocalEval1KV2:
		if err := generateLocalEval1KV2(*outDir, *suitePath); err != nil {
			exitf("generate seed: %v", err)
		}
	case presetLocalEvalRelational1KV1:
		if err := generateRelationalSeed(*preset, 100, *outDir, *suitePath); err != nil {
			exitf("generate seed: %v", err)
		}
	case presetLocalTrainRelational100K:
		if err := generateRelationalSeed(*preset, 10000, *outDir, *suitePath); err != nil {
			exitf("generate seed: %v", err)
		}
	case presetFeedbackRecallHardcases:
		if err := generateFeedbackRecallHardcasesV1(*outDir, *suitePath); err != nil {
			exitf("generate seed: %v", err)
		}
	default:
		exitf("unsupported preset %q", *preset)
	}
	fmt.Printf("generated %s in %s and %s\n", *preset, *outDir, *suitePath)
}

