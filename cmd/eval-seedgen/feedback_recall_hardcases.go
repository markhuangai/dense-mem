func generateFeedbackRecallHardcasesV1(outDir, suitePath string) error {
	generated := buildFeedbackRecallHardcasesV1()
	corpusCount := 0
	hardNegativeCount := 0
	dreamCount := 0
	for _, item := range generated {
		corpusCount += len(item.Corpus)
		hardNegativeCount += len(item.HardNegatives)
		dreamCount += len(item.Dreams)
	}
	manifest := evalharness.SeedManifest{
		SchemaVersion:     evalharness.SeedSchemaVersion,
		SeedID:            presetFeedbackRecallHardcases,
		Description:       "Feedback-derived recall hardcases for exact identifiers, metadata recall text, authority tiers, and dream relevance filtering.",
		GeneratedAt:       "2026-07-08T00:00:00Z",
		CorpusFile:        "corpus.jsonl",
		CasesFile:         "cases.jsonl",
		QrelsFile:         "qrels.jsonl",
		AnswersFile:       "answers.jsonl",
		HardNegativesFile: "hard_negatives.jsonl",
		TransformsFile:    "transforms.jsonl",
		DreamsFile:        "expected_dreams.jsonl",
		LicensesFile:      "licenses.md",
		Counts: map[string]int{
			"cases":          len(generated),
			"corpus":         corpusCount,
			"docs_per_case":  3,
			"qrels":          len(generated),
			"answers":        len(generated),
			"transforms":     len(generated),
			"hard_negatives": hardNegativeCount,
			"dreams":         dreamCount,
		},
		Sources: []evalharness.SeedSource{
			{
				Name:    "dense-mem synthetic recall feedback hardcases",
				License: "Project-local synthetic data",
				Notes:   "Generated by cmd/eval-seedgen from observed recall feedback failure modes; contains no production data.",
			},
		},
	}

	corpus := make([]evalharness.CorpusItem, 0, corpusCount)
	cases := make([]evalharness.Case, 0, len(generated))
	qrels := make([]evalharness.QRel, 0, len(generated))
	answers := make([]evalharness.AnswerLabel, 0, len(generated))
	hardNegatives := make([]hardNegativeRow, 0, hardNegativeCount)
	transforms := make([]transformRow, 0, len(generated))
	dreams := make([]evalharness.ExpectedDream, 0, dreamCount)
	suite := make([]evalharness.SuiteCase, 0, len(generated))
	for _, item := range generated {
		corpus = append(corpus, item.Corpus...)
		cases = append(cases, item.Case)
		qrels = append(qrels, item.QRel)
		answers = append(answers, item.Answer)
		hardNegatives = append(hardNegatives, item.HardNegatives...)
		transforms = append(transforms, item.Transform)
		dreams = append(dreams, item.Dreams...)
		suite = append(suite, item.SuiteCase)
	}
	if err := writeJSONFile(filepath.Join(outDir, "seed_manifest.json"), manifest); err != nil {
		return err
	}
	if err := writeJSONL(filepath.Join(outDir, "corpus.jsonl"), corpus); err != nil {
		return err
	}
	if err := writeJSONL(filepath.Join(outDir, "cases.jsonl"), cases); err != nil {
		return err
	}
	if err := writeJSONL(filepath.Join(outDir, "qrels.jsonl"), qrels); err != nil {
		return err
	}
	if err := writeJSONL(filepath.Join(outDir, "answers.jsonl"), answers); err != nil {
		return err
	}
	if err := writeJSONL(filepath.Join(outDir, "hard_negatives.jsonl"), hardNegatives); err != nil {
		return err
	}
	if err := writeJSONL(filepath.Join(outDir, "transforms.jsonl"), transforms); err != nil {
		return err
	}
	if err := writeJSONL(filepath.Join(outDir, "expected_dreams.jsonl"), dreams); err != nil {
		return err
	}
	if err := writeText(filepath.Join(outDir, "licenses.md"), feedbackHardcaseLicense()); err != nil {
		return err
	}
	return writeJSONL(suitePath, suite)
}

