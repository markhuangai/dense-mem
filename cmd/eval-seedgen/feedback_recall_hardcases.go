func feedbackGeneratedCase(
	caseID, category, query, expected, answer string,
	mustInclude, mustNotInclude []string,
	corpus []evalharness.CorpusItem,
	qrelMutator func(*evalharness.QRel),
	extraMutators ...func(*generatedCase),
) generatedCase {
	requiredID := caseID + "_required"
	negative1ID := caseID + "_negative_01"
	negative2ID := caseID + "_negative_02"
	slices := []string{"feedback_regression", "adversarial", category}
	qrel := evalharness.QRel{
		CaseID: caseID,
		RequiredRefs: []evalharness.Ref{
			{Type: "fragment", SourceDocID: requiredID, Grade: 3, Reason: "required feedback hardcase record"},
		},
		BadRefs: []evalharness.Ref{
			{Type: "fragment", SourceDocID: negative1ID, Grade: -1, Reason: "feedback hardcase decoy"},
			{Type: "fragment", SourceDocID: negative2ID, Grade: -1, Reason: "feedback hardcase decoy"},
		},
		RequiredEvidenceRefs: []evalharness.Ref{
			{Type: "fragment", SourceDocID: requiredID, Grade: 1, Reason: "required source evidence"},
		},
		BadEvidenceRefs: []evalharness.Ref{
			{Type: "fragment", SourceDocID: negative1ID, Grade: -1, Reason: "misleading source evidence"},
			{Type: "fragment", SourceDocID: negative2ID, Grade: -1, Reason: "misleading source evidence"},
		},
	}
	if qrelMutator != nil {
		qrelMutator(&qrel)
	}
	gc := generatedCase{
		Case: evalharness.Case{
			CaseID:           caseID,
			Query:            query,
			TaskType:         "memory_recall",
			Difficulty:       "hard",
			Slices:           slices,
			ExpectedBehavior: expected,
			KnownAt:          "2026-07-08T00:00:00Z",
			Limit:            5,
		},
		SuiteCase: evalharness.SuiteCase{CaseID: caseID, Weight: 1, Slices: slices},
		Corpus:    corpus,
		QRel:      qrel,
		Answer: evalharness.AnswerLabel{
			CaseID:             caseID,
			ReferenceAnswer:    answer,
			MustInclude:        mustInclude,
			MustNotInclude:     mustNotInclude,
			ExpectedBehavior:   expected,
			GroundednessPolicy: "Use the exact feedback hardcase memory; reject close identifier, source, and dream decoys.",
		},
		HardNegatives: []hardNegativeRow{
			{CaseID: caseID, Category: category, SourceDocID: negative1ID, Reason: "Close lexical overlap but wrong identifier, authority, or anchor."},
			{CaseID: caseID, Category: category, SourceDocID: negative2ID, Reason: "Neighbor or stale feedback item that should not answer the query."},
		},
		Transform: transformRow{CaseID: caseID, Category: category, Transform: expected, DocsPerCase: len(corpus), RequiredDocID: requiredID},
	}
	for _, mutate := range extraMutators {
		mutate(&gc)
	}
	return gc
}

func feedbackCorpusItem(sourceDocID, title, content, category, role string, quality float64, caseID string, metadata map[string]any, claims ...evalharness.TypedClaim) evalharness.CorpusItem {
	itemMetadata := map[string]any{
		"case_id":  caseID,
		"role":     role,
		"category": category,
	}
	for key, value := range metadata {
		itemMetadata[key] = value
	}
	for i := range claims {
		if claims[i].IdempotencyKey == "" {
			claims[i].IdempotencyKey = fmt.Sprintf("eval:%s:claim:%d", sourceDocID, i+1)
		}
		if claims[i].ExtractConf == 0 {
			claims[i].ExtractConf = 0.98
		}
		if claims[i].ResolutionConf == 0 {
			claims[i].ResolutionConf = 0.98
		}
		if claims[i].ExtractionModel == "" {
			claims[i].ExtractionModel = "dense-mem.eval-feedback-seedgen"
		}
		if claims[i].ExtractionVersion == "" {
			claims[i].ExtractionVersion = "v1"
		}
		if claims[i].PipelineRunID == "" {
			claims[i].PipelineRunID = "eval:" + sourceDocID
		}
		if claims[i].Classification == nil {
			claims[i].Classification = map[string]any{}
		}
		claims[i].Classification["case_id"] = caseID
		claims[i].Classification["category"] = category
		claims[i].Classification["role"] = role
		claims[i].Classification["confidentiality"] = "public"
		claims[i].Classification["pii"] = "synthetic"
	}
	return evalharness.CorpusItem{
		SourceDocID:   sourceDocID,
		Title:         title,
		Content:       content,
		SourceDataset: presetFeedbackRecallHardcases,
		SourceType:    "synthetic",
		Authority:     role,
		SourceQuality: quality,
		Labels:        []string{"eval", "feedback_regression", category, role},
		Metadata:      itemMetadata,
		Claims:        claims,
		AutoPromote:   len(claims) > 0,
	}
}

func feedbackClaim(subject, predicate, object string, classification map[string]any) evalharness.TypedClaim {
	claimClassification := map[string]any{
		"confidentiality": "public",
		"pii":             "synthetic",
	}
	for key, value := range classification {
		claimClassification[key] = value
	}
	return evalharness.TypedClaim{
		Subject:        subject,
		Predicate:      predicate,
		Object:         object,
		Modality:       "assertion",
		Polarity:       "+",
		ExtractConf:    0.98,
		ResolutionConf: 0.98,
		Classification: claimClassification,
	}
}

func feedbackCaseID(index int) string {
	return fmt.Sprintf("%s_%03d", presetFeedbackRecallHardcases, index)
}

